// Renders the official SVG logo to a PNG (email clients don't show SVG) and stores it as base64
// in src/lib/email-logo.ts, so the server bundle carries it without any file tracing.
// Run `npm run email:logo` whenever public/images/logo-medgold.svg changes.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const WIDTH = 420;

const svg = await readFile(`${root}public/images/logo-medgold.svg`);
const png = await sharp(svg, { density: 300 }).resize({ width: WIDTH }).png({ compressionLevel: 9 }).toBuffer();
const { height } = await sharp(png).metadata();

await writeFile(
  `${root}src/lib/email-logo.ts`,
  `// Generated by scripts/build-email-logo.mjs from public/images/logo-medgold.svg. Do not edit.
export const EMAIL_LOGO = {
  cid: "medgold-logo",
  width: ${WIDTH / 2},
  height: ${Math.round((height ?? 0) / 2)},
  base64:
    "${png.toString("base64")}",
} as const;
`,
);

console.log(`email logo: ${WIDTH}x${height}px, ${(png.length / 1024).toFixed(1)} KB`);
