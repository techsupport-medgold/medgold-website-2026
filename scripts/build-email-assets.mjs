// Renders the inline email images and stores them as base64 in src/lib/email-assets.ts,
// so the server bundle carries them without any file tracing. Email clients don't show SVG,
// so the logo becomes a PNG. Run `npm run email:assets` whenever the source images change.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const LOGO_WIDTH = 420;
const BANNER = { width: 1200, height: 525 };

const svg = await readFile(`${root}public/images/logo-medgold.svg`);
const logo = await sharp(svg, { density: 300 })
  .trim()
  .resize({ width: LOGO_WIDTH })
  // The logo is flat teal, gold and red, so 16 colours without dithering keeps it crisp at about 4 KB.
  .png({ palette: true, colours: 16, dither: 0, compressionLevel: 9, effort: 10 })
  .toBuffer();
const { height: logoHeight = 0 } = await sharp(logo).metadata();

const banner = await sharp(`${root}public/images/staffing/nursing.jpg`)
  .resize({ ...BANNER, fit: "cover", position: "centre" })
  .jpeg({ quality: 68, mozjpeg: true, progressive: true })
  .toBuffer();

const entry = (name, cid, width, height, buffer) => `export const ${name} = {
  cid: "${cid}",
  width: ${width},
  height: ${height},
  base64:
    "${buffer.toString("base64")}",
} as const;
`;

await writeFile(
  `${root}src/lib/email-assets.ts`,
  `// Generated by scripts/build-email-assets.mjs. Do not edit.
${entry("EMAIL_LOGO", "medgold-logo", LOGO_WIDTH / 2, Math.round(logoHeight / 2), logo)}
${entry("EMAIL_BANNER", "medgold-careers-banner", BANNER.width / 2, Math.round(BANNER.height / 2), banner)}`,
);

console.log(`email logo: ${LOGO_WIDTH}x${logoHeight}px, ${(logo.length / 1024).toFixed(1)} KB`);
console.log(`email banner: ${BANNER.width}x${BANNER.height}px, ${(banner.length / 1024).toFixed(1)} KB`);
